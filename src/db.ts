import { drizzle } from "drizzle-orm/libsql";
import { migrate as runMigrations } from "drizzle-orm/libsql/migrator";
import { createClient } from "@libsql/client";
import * as schema from "./schema.ts";

export type Db = ReturnType<typeof createDb>;

/** Open a database. Tests pass a temporary file; hosted libSQL also needs a token. */
export function createDb(
  url: string,
  options: { logger?: boolean; authToken?: string } = {},
) {
  const client = createClient({
    url,
    ...(options.authToken ? { authToken: options.authToken } : {}),
  });
  const db = drizzle(client, { schema, logger: options.logger ?? false });
  return { db, client };
}

/** Apply the migration files generated by Drizzle Kit from schema.ts. */
export async function migrate({ db }: Db) {
  await runMigrations(db, { migrationsFolder: "./drizzle" });
}
